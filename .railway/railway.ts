function preserveVariables(names: readonly string[]) {
  return Object.fromEntries(names.map((name) => [name, preserve()]));
}

export default defineRailway((ctx) => {
  if (!ctx.isEnvironment('production') && !ctx.isEnvironment('staging')) {
    throw new Error(`Unsupported Railway environment: ${ctx.environment}`);
  }

  const production = ctx.isEnvironment('production');
  const backend = service(production ? 'production' : 'genuine-exploration', {
    source: github('ZweiHenky/tenka-back', {
      branch: production ? 'main' : 'testing',
      checkSuites: false,
    }),
    env: preserveVariables(production ? productionVariables : stagingVariables),
    build: {
      builder: 'RAILPACK',
      buildCommand: 'pnpm build',
    },
    deploy: {
      startCommand: 'pnpm start',
      healthcheckPath: '/ready',
      healthcheckTimeout: 100,
    },
  });

  return project('tenka', { resources: [backend] });
});
